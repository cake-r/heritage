def get_province_coords(region: str) -> list[float]:
    """从完整地区字符串提取省份坐标，如 '江苏苏州' → [118.78, 32.04]"""
    if not region:
        return []
    province = region.split()[0] if " " in region else region[:2]
    for key, coords in PROVINCE_COORDS.items():
        if province in key or key in province:
            return coords
    return []


def extract_province(region: str) -> str:
    """从完整地区提取省份名，如 '江苏苏州' → '江苏'"""
    if not region:
        return ""
    # 直辖市直接返回
    for city in ["北京", "天津", "上海", "重庆"]:
        if region.startswith(city):
            return city
    # 取前两个字符作为省份
    return region[:2] if len(region) >= 2 else region
