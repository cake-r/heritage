def enrich_all():
    print("=" * 60)
    print("Comprehensive Heritage Data Enrichment (ALL 50 items)")
    print("=" * 60)

    with open(HERITAGE_FILE, "r", encoding="utf-8") as f:
        items = json.load(f)

    enriched_count = 0
    for item in items:
        name = item["name"]
        category = item.get("category", "")

        # Check if item has detailed data in DATA dict
        if name in DATA:
            d = DATA[name]
            item["description"] = d["description"]
            item["techniques"] = d["techniques"]
            item["inheritors"] = d["inheritors"]
            item["cultural_meaning"] = d["cultural_meaning"]
            enriched_count += 1
            print(f"  [FULL] {name}")
        else:
            # Check if we have a default description
            if name in DEFAULT_DESCRIPTIONS:
                item["description"] = DEFAULT_DESCRIPTIONS[name]
                print(f"  [DESC] {name}")
            elif len(item.get("description", "")) < 100:
                # Generate a reasonable description
                item["description"] = f"{name}是中国传统{category}艺术的杰出代表，具有悠久的历史和鲜明的地域特色。作为国家级非物质文化遗产，{name}承载着丰富的历史信息和深厚的文化底蕴，体现了中国工匠卓越的技艺水平和独特的审美追求。"

            # Update techniques with rich content
            if len(item.get("techniques", [])) <= 1 or len(str(item["techniques"][0].get("desc", ""))) < 20:
                item["techniques"] = make_techniques(category)

            # Update inheritors with rich content
            if len(item.get("inheritors", [])) <= 1 or all(len(str(i.get("desc", ""))) < 20 for i in item.get("inheritors", [])):
                item["inheritors"] = make_inheritors(name, category)

            # Update cultural meaning
            if len(item.get("cultural_meaning", "")) < 100:
                item["cultural_meaning"] = make_cultural_meaning(name, category)

            enriched_count += 1
            print(f"  [AUTO] {name} ({category})")

    print(f"\nEnriched {enriched_count} items out of {len(items)} total")

    # Save
    with open(HERITAGE_FILE, "w", encoding="utf-8") as f:
        json.dump(items, f, ensure_ascii=False, indent=2)
    print(f"Saved to {HERITAGE_FILE}")

    return items


def reseed(items):
    """Re-seed database with enriched data"""
    from app.models.database import SessionLocal, init_db
    from app.models.exhibition import HeritageItem

    init_db()
    db = SessionLocal()
    try:
        count = db.query(HeritageItem).count()
        print(f"  Clearing {count} existing records...")
        db.query(HeritageItem).delete()
        db.commit()

        for item in items:
            heritage = HeritageItem(
                name=item["name"],
                category=item["category"],
                region=item["region"],
                era=item["era"],
                description=item["description"],
                techniques_json=json.dumps(item["techniques"], ensure_ascii=False),
                inheritors_json=json.dumps(item["inheritors"], ensure_ascii=False),
                images_json=json.dumps(item["images"], ensure_ascii=False),
                cultural_meaning=item["cultural_meaning"],
            )
            db.add(heritage)

        db.commit()
        print(f"  Imported {len(items)} enriched items")
    except Exception as e:
        db.rollback()
        print(f"  Error: {e}")
        raise
    finally:
        db.close()


if __name__ == "__main__":
    items = enrich_all()
    print("\nRe-seeding database...")
    reseed(items)
    print("\nDone! All 50 heritage items now have rich content.")
